DO $$
DECLARE
    request_type_data_type TEXT;
    priority_data_type TEXT;
BEGIN
    SELECT data_type INTO request_type_data_type
    FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'guest_requests'
      AND column_name = 'request_type';

    IF request_type_data_type IN ('integer', 'smallint') THEN
        IF EXISTS (
            SELECT 1 FROM guest_requests
            WHERE request_type IS NOT NULL AND request_type NOT IN (0, 1, 2, 3, 4)
        ) THEN
            RAISE EXCEPTION 'guest_requests.request_type contains an unsupported ordinal';
        END IF;
        ALTER TABLE guest_requests
            ALTER COLUMN request_type TYPE VARCHAR(255)
            USING CASE request_type
                WHEN 0 THEN 'HOUSE_KEEPING'
                WHEN 1 THEN 'MAINTENANCE'
                WHEN 2 THEN 'ROOM_SERVICE'
                WHEN 3 THEN 'AMENITIES'
                WHEN 4 THEN 'VIP_SERVICE'
            END;
    ELSE
        UPDATE guest_requests
        SET request_type = CASE request_type
            WHEN 'House keeping' THEN 'HOUSE_KEEPING'
            WHEN 'Maintenance' THEN 'MAINTENANCE'
            WHEN 'Room service' THEN 'ROOM_SERVICE'
            WHEN 'Amenities' THEN 'AMENITIES'
            WHEN 'VIP Service' THEN 'VIP_SERVICE'
            ELSE request_type
        END;
    END IF;

    SELECT data_type INTO priority_data_type
    FROM information_schema.columns
    WHERE table_schema = current_schema()
      AND table_name = 'guest_requests'
      AND column_name = 'priority';

    IF priority_data_type IN ('integer', 'smallint') THEN
        IF EXISTS (
            SELECT 1 FROM guest_requests
            WHERE priority IS NOT NULL AND priority NOT IN (0, 1, 2)
        ) THEN
            RAISE EXCEPTION 'guest_requests.priority contains an unsupported ordinal';
        END IF;
        ALTER TABLE guest_requests
            ALTER COLUMN priority TYPE VARCHAR(255)
            USING CASE priority
                WHEN 0 THEN 'URGENT'
                WHEN 1 THEN 'NORMAL'
                WHEN 2 THEN 'LOW'
            END;
    ELSE
        UPDATE guest_requests
        SET priority = CASE priority
            WHEN 'Urgent' THEN 'URGENT'
            WHEN 'Normal' THEN 'NORMAL'
            WHEN 'Low' THEN 'LOW'
            ELSE priority
        END;
    END IF;
END $$;

