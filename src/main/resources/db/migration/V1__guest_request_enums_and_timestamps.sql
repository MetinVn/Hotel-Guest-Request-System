ALTER TABLE guest_requests ADD COLUMN IF NOT EXISTS priority VARCHAR(255);
ALTER TABLE guest_requests ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ;
ALTER TABLE guest_requests ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ;
